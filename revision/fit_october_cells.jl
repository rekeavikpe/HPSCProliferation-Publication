include("October20.jl")
length(ARGS)==4||error("Usage: fit_october_cells.jl FIT LINE OUTPUT FREE_NAMES")
fit,line,out,list=ARGS;cfg=TOML.parsefile(joinpath(fit,"calibration.toml"));parent=read_parameters(joinpath(fit,"model5/selected_parameters.csv"),6)
free=isempty(list) ? Symbol[] : Symbol.(split(list,","));all(n->n in REQUESTED5,free)||error("Unapproved cell parameter")
cfg["fixed"]=Dict(string(n)=>getproperty(parent,n) for n in keys(parent) if !(n in free))
ctx=cell_context(line,cfg)
lock_inputs(out,Dict("line"=>line,"free"=>string.(free),"starts"=>get(ENV,"HPSC_REVIEW_STARTS","100"),"budget"=>get(ENV,"HPSC_REVIEW_EVALUATIONS","20000"),"iterations"=>get(ENV,"HPSC_REVIEW_ITERATIONS","3000")),[@__FILE__,joinpath(fit,"model5/selected_parameters.csv")])
p=isempty(free) ? parent : first(fit_new(ctx,6,out))
save_parameters(joinpath(out,"selected_parameters.csv"),p)
open(io->TOML.print(io,cfg),joinpath(out,"calibration.toml"),"w")
write(joinpath(out,"cell_line.txt"),line)
CSV.write(joinpath(out,"observations.csv"),ctx.observations)
CSV.write(joinpath(out,"parameter_policy.csv"),[(parameter=string(n),estimated=n in free,reference_value=getproperty(parent,n),value=getproperty(p,n)) for n in keys(parent)])
CSV.write(joinpath(out,"errors.csv"),vcat(report_metrics(ctx,6,parent;tag="Unchanged ESI-017",cohort=line),report_metrics(ctx,6,p;tag="Recalibrated",cohort=line)))
CSV.write(joinpath(out,"curves.csv"),vcat([merge((strategy="Unchanged ESI-017",),r) for r in export_curves(ctx,6,parent)],[merge((strategy="Recalibrated",),r) for r in export_curves(ctx,6,p)]))
write(joinpath(out,"FIT_COMPLETE"),"Cell fit saved\n")
